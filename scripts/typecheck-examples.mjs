// Type-check the examples that have a tsconfig.json. Each one extends
// `./.celesta/tsconfig.json`, so first copy in the support directory the
// editor's `--init` installs, staged by `pnpm run build:runtime` at
// packages/cli/dist/project-types. Unlike `--init`, this writes nothing but
// `.celesta/`, which ignores itself in Git.
//
//   node scripts/typecheck-examples.mjs [name...]
import { spawnSync } from 'node:child_process';
import { cpSync, existsSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const examples = join(root, 'examples');
const template = join(root, 'packages', 'cli', 'dist', 'project-types');
if (!existsSync(join(template, 'version.json'))) {
  console.error(`Missing ${template}. Run \`pnpm run build:runtime\` first.`);
  process.exit(1);
}
const tsc = join(
  dirname(createRequire(join(root, 'packages', 'cli', 'package.json')).resolve('typescript/package.json')),
  'bin',
  'tsc',
);

const names = process.argv.slice(2);
const targets = names.length
  ? names
  : readdirSync(examples)
      .filter((name) => existsSync(join(examples, name, 'tsconfig.json')))
      .sort();

let failed = 0;
for (const name of targets) {
  const project = join(examples, name);
  if (!existsSync(join(project, 'tsconfig.json'))) {
    console.error(`examples/${name} has no tsconfig.json`);
    failed++;
    continue;
  }
  // The same layout crates/react-bridge/src/project_types.rs installs.
  const support = join(project, '.celesta');
  rmSync(support, { recursive: true, force: true });
  cpSync(template, support, { recursive: true });
  writeFileSync(join(support, '.gitignore'), '# Generated by Celesta and refreshed when Celesta updates.\n*\n');

  console.log(`examples/${name}`);
  const { status } = spawnSync(process.execPath, [tsc, '--noEmit', '-p', project], { stdio: 'inherit' });
  if (status !== 0) failed++;
}
if (failed) {
  console.error(`${failed} of ${targets.length} examples failed the type check.`);
  process.exit(1);
}
